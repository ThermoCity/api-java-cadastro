-- =====================================================================
-- ThermoCity — API Java (camada QUEM)
-- Script de banco: PostgreSQL 18 (Azure), schema public
--
-- O que este script faz:
--   1. Cria a tabela de login (tmc_usuario)
--   2. Prepara tmc_pessoa_sintetica para o CRUD de /pessoas (cadastro real)
--   3. Reatribui a UBS das pessoas vinculadas a unidades que não são UBS
--   4. Cria as tabelas da lista priorizada, dos contatos e dos eventos
--
-- É idempotente: pode rodar mais de uma vez sem duplicar nada.
-- NÃO cria nem altera: tmc_setor, tmc_calor_setor, tmc_servico,
-- tmc_limiar_nivel_calor, tmc_nivel_calor e tabelas de clima (outras camadas).
--
-- Execução: psql "$DB_URL_PSQL" -f scripts/script-bd.sql
-- (a aplicação roda com spring.jpa.hibernate.ddl-auto=none)
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. USUÁRIOS (login) — separado das pessoas acompanhadas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tmc_usuario (
    id_usuario     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    senha          VARCHAR(255) NOT NULL,              -- hash BCrypt
    telefone       VARCHAR(11)  NOT NULL,              -- só dígitos
    cpf            VARCHAR(11)  NOT NULL,              -- só dígitos
    cep            VARCHAR(8)   NOT NULL,
    latitude       DOUBLE PRECISION,
    longitude      DOUBLE PRECISION,
    papel          VARCHAR(20)  NOT NULL,
    ubs_id         VARCHAR(40),                        -- UBS de atuação do AGENTE
    data_criacao   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_tmc_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uk_tmc_usuario_email UNIQUE (email),
    CONSTRAINT uk_tmc_usuario_cpf UNIQUE (cpf),
    CONSTRAINT ck_tmc_usuario_papel CHECK (papel IN ('CIDADAO', 'AGENTE', 'GESTOR', 'COLETOR')),
    CONSTRAINT ck_tmc_usuario_agente_ubs CHECK (papel <> 'AGENTE' OR ubs_id IS NOT NULL),
    CONSTRAINT fk_tmc_usuario_ubs FOREIGN KEY (ubs_id) REFERENCES tmc_servico (id)
);

-- ---------------------------------------------------------------------
-- 2. PESSOAS ACOMPANHADAS — tmc_pessoa_sintetica vira a tabela do CRUD
--    Sintéticos (sintetico = true) continuam como estão.
--    Cadastros reais entram com sintetico = false e titular_id preenchido.
-- ---------------------------------------------------------------------
ALTER TABLE tmc_pessoa_sintetica
    ADD COLUMN IF NOT EXISTS titular_id      BIGINT,
    ADD COLUMN IF NOT EXISTS data_nascimento DATE,
    ADD COLUMN IF NOT EXISTS endereco        VARCHAR(200),
    ADD COLUMN IF NOT EXISTS cep             VARCHAR(8),
    ADD COLUMN IF NOT EXISTS atualizado_em   TIMESTAMPTZ;

-- id passa a sair da sequence já existente (hoje em 20001)
ALTER TABLE tmc_pessoa_sintetica
    ALTER COLUMN id SET DEFAULT nextval('tmc_seq_pessoa_sintetica');

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_tmc_pessoa_titular') THEN
        ALTER TABLE tmc_pessoa_sintetica
            ADD CONSTRAINT fk_tmc_pessoa_titular
            FOREIGN KEY (titular_id) REFERENCES tmc_usuario (id_usuario);
    END IF;
    -- cadastro real exige titular e consentimento LGPD
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_tmc_pessoa_real') THEN
        ALTER TABLE tmc_pessoa_sintetica
            ADD CONSTRAINT ck_tmc_pessoa_real
            CHECK (sintetico OR (titular_id IS NOT NULL AND consentimento_lgpd));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_tmc_pessoa_titular ON tmc_pessoa_sintetica (titular_id);
CREATE INDEX IF NOT EXISTS ix_tmc_pessoa_ubs     ON tmc_pessoa_sintetica (ubs_ref_id);
CREATE INDEX IF NOT EXISTS ix_tmc_pessoa_nome    ON tmc_pessoa_sintetica (lower(nome));

-- ---------------------------------------------------------------------
-- 3. REATRIBUIÇÃO DE UBS
--    Três registros de tmc_servico com tipo 'UBS' não atendem a população:
--      CNES-8016305  Penitenciária Wellington Rodrigo Segura   (16 pessoas)
--      CNES-8016291  Centro de Ressocialização                 ( 1 pessoa)
--      CNES-118796   Centro de Triagem COVID 19                (214 pessoas)
--    As pessoas vinculadas a eles passam para a UBS válida mais próxima
--    (distância de Haversine). A mesma lista fica em
--    thermocity.ubs.excluidas no application.properties, para o cadastro novo.
-- ---------------------------------------------------------------------
UPDATE tmc_pessoa_sintetica p
   SET (ubs_ref_id, ubs_ref_nome) = (
        SELECT u.id, u.nome
          FROM tmc_servico u
         WHERE u.tipo = 'UBS'
           AND u.id NOT IN ('CNES-8016305', 'CNES-8016291', 'CNES-118796')
         ORDER BY 2 * 6371000 * asin(sqrt(
                    power(sin(radians(u.lat - p.lat) / 2), 2)
                  + cos(radians(p.lat)) * cos(radians(u.lat))
                  * power(sin(radians(u.lon - p.lon) / 2), 2)))
         LIMIT 1)
 WHERE p.ubs_ref_id IN ('CNES-8016305', 'CNES-8016291', 'CNES-118796');

-- Refúgios: tmc_servico não é alterada. A API considera refúgio
--   tipo = 'REFUGIO' AND revisao IN ('manter', 'potencial')   -> 101 locais
-- e ignora 'remover' (27), 'revisar' (26) e 'publico_alvo' (1).

-- ---------------------------------------------------------------------
-- 4. LISTA PRIORIZADA DE BUSCA ATIVA (uma por UBS por dia)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tmc_lista_busca_ativa (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    data_lista    DATE         NOT NULL,
    ubs_id        VARCHAR(40)  NOT NULL,
    nivel_calor   INTEGER      NOT NULL,
    evento_id     VARCHAR(64)  NOT NULL,               -- evento que gerou a lista
    versao_regra  VARCHAR(20)  NOT NULL DEFAULT 'v1',
    status        VARCHAR(10)  NOT NULL DEFAULT 'ABERTA',
    criada_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    encerrada_em  TIMESTAMPTZ,
    CONSTRAINT pk_tmc_lista PRIMARY KEY (id),
    CONSTRAINT uk_tmc_lista_dia_ubs UNIQUE (data_lista, ubs_id),
    CONSTRAINT ck_tmc_lista_nivel CHECK (nivel_calor BETWEEN 3 AND 5),
    CONSTRAINT ck_tmc_lista_status CHECK (status IN ('ABERTA', 'ENCERRADA')),
    CONSTRAINT fk_tmc_lista_ubs FOREIGN KEY (ubs_id) REFERENCES tmc_servico (id)
);

CREATE TABLE IF NOT EXISTS tmc_lista_item (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    lista_id          BIGINT       NOT NULL,
    pessoa_id         BIGINT,                          -- NULL após exclusão (LGPD)
    setor_codigo      VARCHAR(15)  NOT NULL,           -- mantém a cobertura por setor
    posicao           INTEGER      NOT NULL,
    pontuacao         INTEGER      NOT NULL,
    motivos           VARCHAR(500) NOT NULL,           -- ex.: "mora sozinha · 78 anos · setor nota 5"
    status_contato    VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    ultimo_contato_em TIMESTAMPTZ,
    CONSTRAINT pk_tmc_lista_item PRIMARY KEY (id),
    CONSTRAINT uk_tmc_lista_item_pessoa UNIQUE (lista_id, pessoa_id),
    CONSTRAINT uk_tmc_lista_item_posicao UNIQUE (lista_id, posicao),
    CONSTRAINT ck_tmc_lista_item_status CHECK (status_contato IN
        ('PENDENTE', 'CONTATADO_BEM', 'PRECISA_AJUDA', 'NAO_ATENDEU', 'DADOS_INCORRETOS')),
    CONSTRAINT fk_tmc_lista_item_lista FOREIGN KEY (lista_id)
        REFERENCES tmc_lista_busca_ativa (id) ON DELETE CASCADE,
    CONSTRAINT fk_tmc_lista_item_pessoa FOREIGN KEY (pessoa_id)
        REFERENCES tmc_pessoa_sintetica (id) ON DELETE SET NULL,
    CONSTRAINT fk_tmc_lista_item_setor FOREIGN KEY (setor_codigo)
        REFERENCES tmc_setor (codigo)
);

-- ---------------------------------------------------------------------
-- 5. CONTATOS (histórico; anonimizado quando a pessoa é excluída)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tmc_contato (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pessoa_id      BIGINT,                             -- NULL após exclusão (LGPD)
    lista_item_id  BIGINT,
    agente_id      BIGINT        NOT NULL,
    ubs_id         VARCHAR(40)   NOT NULL,
    resultado      VARCHAR(20)   NOT NULL,
    observacao     VARCHAR(1000),                      -- apagada na anonimização
    realizado_em   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_tmc_contato PRIMARY KEY (id),
    CONSTRAINT ck_tmc_contato_resultado CHECK (resultado IN
        ('CONTATADO_BEM', 'PRECISA_AJUDA', 'NAO_ATENDEU', 'DADOS_INCORRETOS')),
    CONSTRAINT fk_tmc_contato_pessoa FOREIGN KEY (pessoa_id)
        REFERENCES tmc_pessoa_sintetica (id) ON DELETE SET NULL,
    CONSTRAINT fk_tmc_contato_item FOREIGN KEY (lista_item_id)
        REFERENCES tmc_lista_item (id) ON DELETE SET NULL,
    CONSTRAINT fk_tmc_contato_agente FOREIGN KEY (agente_id)
        REFERENCES tmc_usuario (id_usuario),
    CONSTRAINT fk_tmc_contato_ubs FOREIGN KEY (ubs_id)
        REFERENCES tmc_servico (id)
);

CREATE INDEX IF NOT EXISTS ix_tmc_contato_pessoa ON tmc_contato (pessoa_id, realizado_em DESC);
CREATE INDEX IF NOT EXISTS ix_tmc_contato_item   ON tmc_contato (lista_item_id);

-- ---------------------------------------------------------------------
-- 6. EVENTOS PROCESSADOS (idempotência do listener RabbitMQ)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tmc_evento_processado (
    evento_id      VARCHAR(64)  NOT NULL,
    data_local     DATE         NOT NULL,
    nivel_novo     INTEGER      NOT NULL,
    acao           VARCHAR(20)  NOT NULL,              -- LISTAS_GERADAS | LISTAS_ENCERRADAS | SEM_ACAO
    listas_afetadas INTEGER     NOT NULL DEFAULT 0,
    processado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_tmc_evento_processado PRIMARY KEY (evento_id),
    CONSTRAINT ck_tmc_evento_nivel CHECK (nivel_novo BETWEEN 1 AND 5)
);

COMMIT;

